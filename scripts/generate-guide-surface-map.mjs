#!/usr/bin/env node
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { validateGraph } from '../src/guide-graph/validate.mjs';

const sha = (value) => createHash('sha256').update(value).digest('hex');
const mid = (value) => `M_${sha(value).slice(0,16)}`;
const esc = (value) => String(value).replaceAll('"', '&quot;');
const getArg = (args, key) => { const i=args.indexOf(key); return i < 0 ? null : args[i+1]; };

export function renderGuideSurfaceMap({ graph, sourceMap, graphBytes, sourceMapBytes }) {
  const sourceIds = new Set((sourceMap.sections ?? []).map((section) => section.id));
  validateGraph(graph, { knownSourceRefs: sourceIds });
  if (graph.guideId !== sourceMap.guideId) throw new Error('graph/source-map guideId mismatch');
  const nodeById = new Map(graph.nodes.map((node) => [node.id, node]));
  const groups = graph.surfaceGroups?.length ? graph.surfaceGroups : [{ name: 'Candidate graph behavior', nodeIds: graph.nodes.map((node) => node.id) }];
  const grouped = new Set();
  for (const group of groups) {
    if (!group.name || !Array.isArray(group.nodeIds)) throw new Error('invalid surface group');
    for (const id of group.nodeIds) {
      if (!nodeById.has(id)) throw new Error(`surface group references unknown node ${id}`);
      if (grouped.has(id)) throw new Error(`surface node appears in more than one group: ${id}`);
      grouped.add(id);
    }
  }
  if (grouped.size !== graph.nodes.length) throw new Error('surface groups must cover every graph node exactly once');
  const projectionHash = sha(Buffer.concat([graphBytes, Buffer.from('\n'), sourceMapBytes]));
  const authority = sourceMap.sourceAuthority ?? {};
  const title = graph.surfaceTitle ?? `${graph.guideId} generated audit map`;
  const out = [
    `# ${title}`, '',
    '> [!warning] Generated audit view',
    '> Do not edit this file or treat it as production graph authority. Regenerate it from the guide-specific candidate graph and source map.',
    `> Projection input: \`${projectionHash}\``,
    `> Guide master authority: \`${authority.repository}@${authority.branch}:${authority.path}\` SHA-256 \`${authority.masterSha256}\``, '',
    '`guide-graphs/candidates/inner-signal-hypnosis.graph.json` is a guide-specific development candidate. It does **not** replace `data/graph-v1.0.0.json` or the current compiled inner-child/somatic bundle.', '',
    `This view shows all ${graph.nodes.length} candidate nodes and ${graph.edges.length} candidate edges. The map is not a requirement to perform every node; the smallest sufficient branch wins.`, '',
    '## Graph surface', '', '```mermaid', 'flowchart TD'
  ];
  for (const group of groups) {
    out.push(`  subgraph ${mid(`group:${group.name}`)}["${esc(group.name)}"]`);
    for (const id of group.nodeIds) {
      const node = nodeById.get(id);
      out.push(`    ${mid(id)}["${esc(id)}<br/>${esc(node.title)}"]`);
    }
    out.push('  end');
  }
  for (const edge of graph.edges) out.push(`  ${mid(edge.from)} -- "${esc(edge.relation)}" --> ${mid(edge.to)}`);
  out.push('```');
  if (graph.primaryJourneys?.length) {
    out.push('', '## Primary user journeys', '');
    graph.primaryJourneys.forEach((journey, i) => out.push(`${i+1}. ${journey}`));
  }
  out.push('', '## Source ledger', '', '| Ref | Heading | Reader-text lines | SHA-256 |', '| --- | --- | ---: | --- |');
  for (const section of sourceMap.sections ?? []) out.push(`| \`${section.id}\` | ${String(section.heading).replaceAll('|','\\|')} | ${section.lineStart}-${section.lineEnd} | \`${section.sha256}\` |`);
  out.push('', '## Source/projection boundary', '',
    '- The article remains canonical in `joel-articles`; this repository stores a hash-bound reader-text source map rather than a competing full article copy.',
    '- Reader-text line numbers refer to the deterministic extraction described in the source map. Native Substack object markup and the later visual-only infographic swap are outside the semantic routing graph.',
    '- The graph is intentionally selective: it encodes practice routing, safety/return logic, epistemic distinctions, practitioner bridging, and app positioning rather than duplicating every paragraph or appendix heading.',
    '- Documentation generation does not itself promote the candidate into the production graph or stable runtime.', '');
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const graphFile = getArg(args,'--graph');
  const sourceMapFile = getArg(args,'--source-map');
  const outFile = getArg(args,'--out');
  if (!graphFile || !sourceMapFile || !outFile) throw new Error('usage: node scripts/generate-guide-surface-map.mjs --graph <graph.json> --source-map <source-map.json> --out <map.md>');
  const graphBytes = await fs.readFile(graphFile);
  const sourceMapBytes = await fs.readFile(sourceMapFile);
  const graph = JSON.parse(graphBytes.toString('utf8'));
  const sourceMap = JSON.parse(sourceMapBytes.toString('utf8'));
  await fs.writeFile(outFile, renderGuideSurfaceMap({ graph, sourceMap, graphBytes, sourceMapBytes }));
  console.log(`Generated ${outFile}`);
}
