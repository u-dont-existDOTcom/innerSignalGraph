import { hkdfSync } from "node:crypto";
import { ValidationError } from "../core/errors.mjs";
import { initializeReadingFirstJournal, advanceReadingFirstJournal } from "./reading-first-order.mjs";

// This narrow guard is used only for an explicitly designated NEW
// reading-first generation. It never changes a historical quote index.
// Original clinical/private source content is not exposed here.
function invariant(ok, code) {
  if (!ok) throw new ValidationError(code, { code });
}

export const JOURNAL_IMPORT_ORDERS = Object.freeze(["legacy_quote_first", "reading_first"]);

export function journalImportOrder(config = {}, { existingState = null } = {}) {
  // The owner's new default applies to genuinely NEW imports. An earlier
  // generation with no recorded import_order was always quote-first, so it
  // retains that behavior when the operator resumes without an override.
  const persistedOrder = existingState
    ? (existingState.import_order ?? "legacy_quote_first") : null;
  const order = config.import_order ?? persistedOrder ?? "reading_first";
  invariant(JOURNAL_IMPORT_ORDERS.includes(order), "JOURNAL_IMPORT_ORDER_INVALID");
  return order;
}

export function readingFirstAttestationKey(stagingKey) {
  invariant(stagingKey instanceof Uint8Array && stagingKey.byteLength >= 32,
    "JOURNAL_READING_FIRST_ATTESTOR_UNAVAILABLE");
  // Separate signing from the existing encrypted staging-store key.
  return Buffer.from(hkdfSync("sha256", stagingKey, Buffer.alloc(0),
    Buffer.from("inner-signal-reading-first-attestation-v1", "utf8"), 32));
}

// Validates the complete private receipt chain *in source order* against a
// protected staging key. Neither a user boolean nor an unsigned summary can
// unlock a new index. The trusted reader's actual source-delivery evidence
// still has to be generated by an authorized reading service.
export function verifiedReadingFirstSynthesis({
  sourceSha256, generation, pageCount, receiptJournal, attestationKey
}) {
  invariant(receiptJournal?.schema_version === 1
    && receiptJournal.source_sha256 === sourceSha256
    && receiptJournal.generation === generation
    && receiptJournal.page_count === pageCount
    && Array.isArray(receiptJournal.transitions)
    && receiptJournal.transitions.length === 3,
    "JOURNAL_READING_FIRST_STAGE_INCOMPLETE");
  let state = initializeReadingFirstJournal({
    source_sha256: sourceSha256, generation, page_count: pageCount,
    archive_receipt_ref: receiptJournal.archive_receipt_ref
  });
  const phases = ["SOURCE_INVENTORIED", "READING_DISPOSITIONED", "LONGITUDINAL_SYNTHESIZED"];
  try {
    for (const [i, step] of receiptJournal.transitions.entries()) {
      invariant(step?.stage === phases[i],
        "JOURNAL_READING_FIRST_STAGE_INCOMPLETE");
      state = advanceReadingFirstJournal(state, {
        to: phases[i], receipt: step.receipt
      }, { attestationSecret: attestationKey });
    }
  } catch (error) {
    // Do not forward private data in errors; structured receipts remain
    // exclusively in the authorized encrypted journal store.
    if (typeof error?.code === "string" && error.code.startsWith("JOURNAL_READING_FIRST_")) throw error;
    throw new ValidationError("JOURNAL_READING_FIRST_STAGE_INVALID",
      { code: "JOURNAL_READING_FIRST_STAGE_INVALID" });
  }
  invariant(state.phase === "LONGITUDINAL_SYNTHESIZED",
    "JOURNAL_READING_FIRST_STAGE_INCOMPLETE");
  invariant(state.source_coverage?.pending === 0,
    "JOURNAL_READING_FIRST_REVIEW_PENDING");
  return Object.freeze({
    phase: state.phase,
    generation: state.generation,
    reviewed_pages: state.source_coverage.reviewed,
    synthesized_receipt_ref: state.milestone_receipts.LONGITUDINAL_SYNTHESIZED
  });
}
