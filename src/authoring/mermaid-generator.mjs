import { sha256Bytes } from "./canonical-json.mjs";
import { activeOverlays } from "./overlay.mjs";

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function mermaidId(type, stableId) {
  return `M_${sha256Bytes(Buffer.from(`${type}\0${stableId}`, "utf8")).slice(0, 16)}`;
}

export function escapeMermaidLabel(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("[", "&#91;")
    .replaceAll("]", "&#93;")
    .replaceAll("{", "&#123;")
    .replaceAll("}", "&#125;")
    .replaceAll("\n", "<br/>");
}

function graphForMap(bundle, mapId) {
  if (mapId === "inner-child") return bundle.graphs.find((graph) => graph.graphId === "inner-child-directed-graph");
  if (mapId === "somatic") return bundle.graphs.find((graph) => graph.graphId === "somatic-directed-graph");
  throw new Error(`Unsupported generated map: ${mapId}`);
}

export function buildMermaidModel({ bundle, registries, mapId }) {
  const graph = graphForMap(bundle, mapId);
  if (!graph) throw new Error(`Missing compiled graph for map ${mapId}.`);
  const nodes = [...graph.nodes].sort((left, right) => compareText(left.id, right.id));
  const edges = [...graph.edges].sort((left, right) => compareText(`${left.from}\0${left.relation}\0${left.to}`, `${right.from}\0${right.relation}\0${right.to}`));
  return { graph, nodes, edges, overlays: activeOverlays(registries, { mapId }) };
}

export function renderMermaidMap({ bundle, registries, mapId, projectionInputSha256 }) {
  const model = buildMermaidModel({ bundle, registries, mapId });
  const lines = [
    "# Inner-child therapy generated audit map",
    "",
    "> [!warning] Generated audit view",
    "> Do not edit this file or treat it as executable authority. Regenerate it with `npm run authoring:maps`.",
    `> Projection input: \`${projectionInputSha256}\``,
    `> Compiled bundle: \`${bundle.version}\``,
    "",
    "Compiled graph JSON remains executable development authority. Dashed overlay relationships are owner-approved documentation only and are not planner input.",
    "",
    "This is an inner-child-scoped view: all 19 compiled inner-child nodes and all 10 compiled inner-child edges are shown. It is not a whole-bundle view.",
    "",
    "The map is not a linear requirement to perform every node. The smallest sufficient branch wins.",
    "",
    "```mermaid",
    "flowchart TD",
    `  subgraph ${mermaidId("subgraph", "compiled")}["Compiled graph behavior"]`
  ];
  for (const node of model.nodes) {
    lines.push(`    ${mermaidId("node", node.id)}["${escapeMermaidLabel(`${node.id}\n${node.title}`)}"]`);
  }
  lines.push("  end");
  for (const edge of model.edges) {
    lines.push(`  ${mermaidId("node", edge.from)} -- "${escapeMermaidLabel(edge.relation)}" --> ${mermaidId("node", edge.to)}`);
  }
  if (model.overlays.length) {
    lines.push(`  subgraph ${mermaidId("subgraph", "overlays")}["Owner-approved, not compiled"]`);
    for (const item of model.overlays) {
      lines.push(`    ${mermaidId("overlay", item.id)}["${escapeMermaidLabel(`${item.id}\nOWNER-APPROVED / NOT COMPILED\n${item.title}`)}"]`);
    }
    lines.push("  end");
    for (const item of model.overlays) {
      for (const anchor of item.anchorNodeIds) {
        lines.push(`  ${mermaidId("overlay", item.id)} -. "${escapeMermaidLabel(`${item.relation} · NOT COMPILED`)}" .-> ${mermaidId("node", anchor)}`);
      }
    }
  }
  lines.push("  classDef compiled fill:#eef4ff,stroke:#2855a6,stroke-width:2px");
  lines.push("  classDef overlay fill:#fff7e6,stroke:#9a6700,stroke-width:2px,stroke-dasharray: 6 4");
  if (model.nodes.length) lines.push(`  class ${model.nodes.map((node) => mermaidId("node", node.id)).join(",")} compiled`);
  if (model.overlays.length) lines.push(`  class ${model.overlays.map((item) => mermaidId("overlay", item.id)).join(",")} overlay`);
  lines.push("```", "", "## Authority legend", "", "- Solid nodes and arrows: exact compiled graph records.", "- Dashed relationships: owner-approved documentation overlays; not compiled and not executable.", "- Canvas geometry, Mermaid layout, links, and visual grouping have no runtime meaning.", "", "## Maintenance", "", "Run `npm run authoring:maps:check`. Update graph authority through validated proposals and the existing owner-decision lifecycle, never by editing this map.", "");
  const output = lines.join("\n");
  validateGeneratedMermaid({ markdown: output, model });
  return output;
}

export function validateGeneratedMermaid({ markdown, model }) {
  const blocks = [...markdown.matchAll(/```mermaid\n([\s\S]*?)\n```/g)];
  if (blocks.length !== 1) throw Object.assign(new Error("Generated map must contain exactly one Mermaid block."), { code: "MERMAID_SUBSET_INVALID" });
  const lines = blocks[0][1].split("\n");
  const safe = [
    /^flowchart TD$/,
    /^  subgraph M_[a-f0-9]{16}\["[^"\r\n]*"\]$/,
    /^  end$/,
    /^    M_[a-f0-9]{16}\["[^"\r\n]*"\]$/,
    /^  M_[a-f0-9]{16} -- "[^"\r\n]*" --> M_[a-f0-9]{16}$/,
    /^  M_[a-f0-9]{16} -\. "[^"\r\n]*" \.-> M_[a-f0-9]{16}$/,
    /^  classDef (?:compiled|overlay) [a-zA-Z0-9:#,\-. ]+$/,
    /^  class M_[a-f0-9]{16}(?:,M_[a-f0-9]{16})* (?:compiled|overlay)$/
  ];
  for (const line of lines) {
    if (!safe.some((pattern) => pattern.test(line))) throw Object.assign(new Error(`Generated Mermaid line is outside the validated subset: ${line}`), { code: "MERMAID_SUBSET_INVALID" });
  }
  for (const node of model.nodes) {
    const id = mermaidId("node", node.id);
    if (lines.filter((line) => line.startsWith(`    ${id}[`)).length !== 1) throw new Error(`Compiled node is not declared exactly once: ${node.id}`);
  }
  for (const edge of model.edges) {
    const prefix = `  ${mermaidId("node", edge.from)} -- "${escapeMermaidLabel(edge.relation)}" --> ${mermaidId("node", edge.to)}`;
    if (lines.filter((line) => line === prefix).length !== 1) throw new Error(`Compiled edge is not emitted exactly once: ${edge.from}/${edge.relation}/${edge.to}`);
  }
  for (const item of model.overlays) {
    const id = mermaidId("overlay", item.id);
    const declarations = lines.filter((line) => line.startsWith(`    ${id}[`));
    if (declarations.length !== 1 || !declarations[0].includes("OWNER-APPROVED / NOT COMPILED")) throw new Error(`Overlay is not visibly emitted exactly once: ${item.id}`);
    if (lines.some((line) => line.startsWith(`    ${mermaidId("node", item.id)}[`))) throw new Error(`Overlay leaked into compiled-node inventory: ${item.id}`);
  }
  return true;
}
