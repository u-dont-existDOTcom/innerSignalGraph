// Generated served view of what sits inside the inner-child map's boxes (owner answer 378a, 20 Nov 2026).
// The Mermaid map carries only box titles and arrows; this file carries each box's advice and cautions and the
// cross-guide routes, so a chat that loads the skill receives them without the planner.
const FIELDS = Object.freeze([
  ["recommendations", "Do"],
  ["effects.requiredNuance", "Keep in mind"],
  ["avoid", "Avoid"],
  ["effects.forbiddenOverclaims", "Never claim"]
]);

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function values(node, name) {
  const list = name.startsWith("effects.") ? node.effects?.[name.slice(8)] : node[name];
  return Array.isArray(list) ? list : [];
}

function oneLine(value) {
  return String(value).replace(/\s+/gu, " ").trim();
}

export function boxGuidanceGraphs(bundle) {
  const innerChild = bundle.graphs.find((graph) => graph.graphId === "inner-child-directed-graph");
  const crossGuide = bundle.graphs.find((graph) => graph.graphId === "inner-child-somatic-cross-guide");
  if (!innerChild || !crossGuide) throw new Error("Box guidance needs the compiled inner-child and cross-guide graphs.");
  return { innerChild, crossGuide };
}

export function renderBoxGuidance({ bundle }) {
  const { innerChild, crossGuide } = boxGuidanceGraphs(bundle);
  const titles = new Map(bundle.graphs.flatMap((graph) => graph.nodes.map((node) => [node.id, node.title])));
  const listed = new Set([...innerChild.nodes, ...crossGuide.nodes].map((node) => node.id));
  const order = (left, right) => left.tier - right.tier || right.priority - left.priority || compareText(left.id, right.id);
  const lines = [
    "# Inside the map's boxes: advice and cautions",
    "",
    "> [!warning] Generated view",
    "> Do not edit this file or treat it as executable authority. Regenerate it with `npm run authoring:maps`.",
    `> Compiled bundle: \`${bundle.version}\``,
    "",
    "These are instructions to InnerSignal. `references/INNER-CHILD-THERAPY-MAP.md` shows the boxes of the inner-child map by title, with their arrows. This file holds what is inside each box (its advice and its cautions), then the cross-guide routes that connect inner-child work with relationships, community, somatic work, altered states, pain, grief and gratitude.",
    "",
    "Use only the boxes that fit this person and this moment. They are not a checklist or a script, and the smallest sufficient step wins. Boxes are listed in the planner's order: lower tier first (safety first), then higher priority. Where a box and `SKILL.md` or another reference seem to differ, keep the safer reading and the person's own words. Do not mention boxes, their IDs or the map to the person.",
    "",
    `Each box lists: Do (its advice), Keep in mind (distinctions to keep), Avoid and Never claim (its cautions), and Leads to (its arrows). ${innerChild.nodes.length} inner-child boxes and ${crossGuide.nodes.length} cross-guide routes.`,
    ""
  ];
  const section = (graph, heading) => {
    lines.push(`## ${heading}`, "");
    for (const node of [...graph.nodes].sort(order)) {
      lines.push(`### ${node.id}: ${oneLine(node.title)}`, "");
      for (const [name, label] of FIELDS) for (const value of values(node, name)) lines.push(`- ${label}: ${oneLine(value)}`);
      const arrows = graph.edges
        .filter((edge) => edge.from === node.id)
        .sort((left, right) => compareText(`${left.relation}\0${left.to}`, `${right.relation}\0${right.to}`))
        .map((edge) => `${edge.relation} ${edge.to}${listed.has(edge.to) ? "" : ` (${oneLine(titles.get(edge.to) ?? "")})`}`);
      if (arrows.length) lines.push(`- Leads to: ${arrows.join("; ")}`);
      lines.push("");
    }
  };
  section(innerChild, "Inner-child boxes");
  section(crossGuide, "Cross-guide routes");
  const output = `${lines.join("\n").replace(/\n+$/u, "")}\n`;
  if (output.includes("references/") && /references\/(?!INNER-CHILD-THERAPY-MAP\.md`)/u.test(output.replaceAll("`references/INNER-CHILD-THERAPY-MAP.md`", ""))) {
    throw new Error("Box guidance may name only served reference paths.");
  }
  return output;
}
